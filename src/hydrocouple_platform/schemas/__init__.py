"""Published JSON Schemas.

``hydrocouple/`` holds unchanged copies of the HydroCoupleSDK schemas the runner
validates against. ``platform/`` holds this package's contracts, generated by
``python -m hydrocouple_platform.schemas`` and checked by the test suite.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from ..contracts import agent, capabilities, errors, jobs, manifests, requests

CONTRACTS = {
    "job-spec-1.json": jobs.JobSpec,
    "adapter-capabilities-1.json": capabilities.AdapterCapabilities,
    "agent-poll-request-1.json": agent.PollRequest,
    "agent-poll-response-1.json": agent.PollResponse,
    "agent-heartbeat-1.json": agent.Heartbeat,
    "agent-heartbeat-ack-1.json": agent.HeartbeatAck,
    "agent-attempt-result-1.json": agent.AttemptResult,
    "agent-grant-fulfillment-1.json": agent.GrantFulfillment,
    "event-1.json": agent.Event,
    "revision-manifest-1.json": manifests.RevisionManifest,
    "attempt-manifest-1.json": manifests.AttemptManifest,
    "run-request-1.json": requests.RunRequest,
    "run-accepted-1.json": requests.RunAccepted,
    "estimate-1.json": requests.Estimate,
    "error-1.json": errors.ErrorBody,
}

PLATFORM_DIR = Path(__file__).parent / "platform"


def render() -> dict[str, str]:
    out = {}
    for name, model in CONTRACTS.items():
        schema = model.model_json_schema(by_alias=True)
        schema = {"$schema": "https://json-schema.org/draft/2020-12/schema",
                  "$id": f"https://hydrocouple.org/schema/platform/{name}", **schema}
        out[name] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    return out


def main() -> int:
    PLATFORM_DIR.mkdir(exist_ok=True)
    for name, text in render().items():
        (PLATFORM_DIR / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(CONTRACTS)} schemas to {PLATFORM_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
